let activeTargetRequestId = null;

function escapeHtml(str) {
  if (!str) return '';
  return String(str)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#039;');
}

function showToast(msg, type = 'info') {
  if (window.showToastMessage) {
    window.showToastMessage(msg, type);
  } else {
    console.log(`[Toast ${type}] ${msg}`);
  }
}

function updateStepperActiveStep(stepNumber) {
  const stepItems = document.querySelectorAll('.dsar-step-item');
  stepItems.forEach(item => {
    const step = parseInt(item.getAttribute('data-step') || '1', 10);
    if (step <= stepNumber) {
      item.classList.add('active');
    } else {
      item.classList.remove('active');
    }
  });
}

function formatSystemName(systemName, tableName) {
  const isFile = (systemName || '').toLowerCase().includes('file') || (tableName || '').toLowerCase().includes('history');
  const typeLabel = isFile ? '📁 File Storage & Audit Logs' : '🗄️ PostgreSQL Database';
  const nameLabel = tableName || systemName || 'System Table';

  return `
    <div style="display:flex; flex-direction:column; gap:2px;">
      <div style="font-weight:700; color:var(--text-bright); font-size:0.88rem; font-family:monospace;">${escapeHtml(nameLabel)}</div>
      <div style="font-size:0.72rem; color:var(--text-muted); font-weight:600;">${escapeHtml(typeLabel)}</div>
    </div>
  `;
}

function generateFallbackCypherScript(graph) {
  const nodes = graph?.nodes || [];
  const edges = graph?.edges || [];
  const root = graph?.rootPerson || 'Data Subject';
  const rootId = 'person_' + root.toLowerCase().replace(/[^a-z0-9]/g, '_');

  let script = `// ========================================================\n// Neo4j Cypher Graph Script: Identity Cluster for '${root}'\n// Auto-Generated by Segmento Protect AI Knowledge Graph Engine\n// ========================================================\n\nMERGE (${rootId}:PersonRoot {id: "${rootId}", name: "${root}"})\n`;

  nodes.forEach(n => {
    if (n.type === 'CANONICAL_PERSON_ROOT') return;
    const nid = (n.id || '').replace(/[^a-zA-Z0-9_]/g, '_');
    const label = (n.label || '').replace(/"/g, '\\"');
    if (n.type === 'NAME_ALIAS') {
      script += `MERGE (${nid}:NameAlias {id: "${nid}", alias: "${label}"})\n`;
    } else if (n.type === 'EMAIL_IDENTIFIER') {
      script += `MERGE (${nid}:EmailIdentifier {id: "${nid}", email: "${label}"})\n`;
    } else if (n.type === 'PHONE_IDENTIFIER') {
      script += `MERGE (${nid}:PhoneIdentifier {id: "${nid}", phone: "${label}"})\n`;
    } else if (n.type === 'SYSTEM_RECORD' || n.type === 'DISCOVERED_RECORD') {
      script += `MERGE (${nid}:DatabaseRecord {id: "${nid}", record: "${label}"})\n`;
    } else {
      script += `MERGE (${nid}:IdentityNode {id: "${nid}", label: "${label}"})\n`;
    }
  });

  edges.forEach(e => {
    const src = (e.source || '').replace(/[^a-zA-Z0-9_]/g, '_');
    const tgt = (e.target || '').replace(/[^a-zA-Z0-9_]/g, '_');
    const rel = e.relationship || 'CONNECTED_TO';
    const conf = e.confidence || '100%';
    script += `MERGE (${src})-[:${rel} {confidence: "${conf}"}]->(${tgt})\n`;
  });

  script += `\nMATCH (root:PersonRoot)-[r*1..2]-(connected) RETURN root, r, connected;`;
  return script;
}

function renderVisualSvgGraph(nodes, edges) {
  const canvas = document.getElementById('dsar-graph-visual-canvas');
  if (!canvas) return;

  if (!nodes || nodes.length === 0) {
    canvas.innerHTML = `<span style="font-size:0.8rem; color:var(--text-muted);">No graph nodes to display.</span>`;
    return;
  }

  const width = 740;
  const height = 260;
  const cx = width / 2;
  const cy = height / 2;

  // Identify root node
  const rootNode = nodes.find(n => n.type === 'CANONICAL_PERSON_ROOT') || nodes[0];
  const orbitNodes = nodes.filter(n => n !== rootNode);
  const totalOrbit = orbitNodes.length || 1;
  const radiusX = 250;
  const radiusY = 95;

  const nodePositions = new Map();
  nodePositions.set(rootNode.id, { x: cx, y: cy, node: rootNode });

  orbitNodes.forEach((n, idx) => {
    const angle = (2 * Math.PI * idx) / totalOrbit - Math.PI / 2;
    const x = cx + radiusX * Math.cos(angle);
    const y = cy + radiusY * Math.sin(angle);
    nodePositions.set(n.id, { x, y, node: n });
  });

  // Build SVG lines for edges
  let svgLines = '';
  (edges || []).forEach(e => {
    const src = nodePositions.get(e.source) || { x: cx, y: cy };
    const tgt = nodePositions.get(e.target) || { x: cx, y: cy };
    const midX = (src.x + tgt.x) / 2;
    const midY = (src.y + tgt.y) / 2;
    const relText = (e.relationship || '').replace('HAS_', '').replace('_', ' ');

    svgLines += `
      <g>
        <line x1="${src.x}" y1="${src.y}" x2="${tgt.x}" y2="${tgt.y}" stroke="rgba(6,182,212,0.4)" stroke-width="1.8" stroke-dasharray="3,3" />
        <rect x="${midX - 35}" y="${midY - 8}" width="70" height="15" rx="3" fill="#0b1329" stroke="rgba(6,182,212,0.3)" stroke-width="0.8" />
        <text x="${midX}" y="${midY + 3}" fill="#38bdf8" font-size="8" font-family="monospace" font-weight="600" text-anchor="middle">${escapeHtml(relText)}</text>
      </g>
    `;
  });

  // Build SVG circles and labels for nodes
  let svgNodes = '';
  nodePositions.forEach((pos) => {
    const n = pos.node;
    const isRoot = n.type === 'CANONICAL_PERSON_ROOT';
    const r = isRoot ? 24 : 17;

    let fill = '#0ea5e9';
    let stroke = '#38bdf8';
    let icon = '🏷️';

    if (isRoot) {
      fill = 'rgba(16,185,129,0.35)';
      stroke = '#10b981';
      icon = '👤';
    } else if (n.type === 'NAME_ALIAS') {
      fill = 'rgba(245,158,11,0.25)';
      stroke = '#f59e0b';
      icon = '🔤';
    } else if (n.type === 'EMAIL_IDENTIFIER') {
      fill = 'rgba(139,92,246,0.25)';
      stroke = '#8b5cf6';
      icon = '✉️';
    } else if (n.type === 'PHONE_IDENTIFIER') {
      fill = 'rgba(59,130,246,0.25)';
      stroke = '#3b82f6';
      icon = '📱';
    } else if (n.type === 'SYSTEM_RECORD' || n.type === 'DISCOVERED_RECORD') {
      fill = 'rgba(20,184,166,0.25)';
      stroke = '#14b8a6';
      icon = '🗄️';
    } else if (n.type === 'NLP_EXTRACTED_ENTITY') {
      fill = 'rgba(236,72,153,0.25)';
      stroke = '#ec4899';
      icon = '🤖';
    }

    const shortLabel = (n.label || '').length > 20 ? (n.label || '').slice(0, 18) + '…' : (n.label || '');

    svgNodes += `
      <g style="cursor:pointer;" class="graph-node-group">
        <circle cx="${pos.x}" cy="${pos.y}" r="${r + 5}" fill="${stroke}" opacity="0.18" />
        <circle cx="${pos.x}" cy="${pos.y}" r="${r}" fill="${fill}" stroke="${stroke}" stroke-width="2" />
        <text x="${pos.x}" y="${pos.y + 4.5}" font-size="${isRoot ? 15 : 12}" text-anchor="middle">${icon}</text>
        <rect x="${pos.x - 50}" y="${pos.y + r + 3}" width="100" height="16" rx="3" fill="rgba(15,23,42,0.9)" stroke="rgba(255,255,255,0.15)" stroke-width="0.8" />
        <text x="${pos.x}" y="${pos.y + r + 14}" fill="#f1f5f9" font-size="9" font-weight="${isRoot ? '700' : '600'}" font-family="sans-serif" text-anchor="middle">${escapeHtml(shortLabel)}</text>
      </g>
    `;
  });

  canvas.innerHTML = `
    <svg width="100%" height="100%" viewBox="0 0 ${width} ${height}" preserveAspectRatio="xMidYMid meet" style="overflow:visible;">
      <defs>
        <radialGradient id="glowGrad" cx="50%" cy="50%" r="50%">
          <stop offset="0%" stop-color="#06b6d4" stop-opacity="0.18"/>
          <stop offset="100%" stop-color="#06b6d4" stop-opacity="0"/>
        </radialGradient>
      </defs>
      <circle cx="${cx}" cy="${cy}" r="${radiusX + 30}" fill="url(#glowGrad)" />
      ${svgLines}
      ${svgNodes}
    </svg>
  `;
}

function renderIdentityGraphCluster(graph) {
  const container = document.getElementById('dsar-graph-nodes-container');
  const countEl = document.getElementById('dsar-graph-node-count');
  const cypherCodeEl = document.getElementById('dsar-cypher-code');
  if (!container) return;

  const nodes = graph?.nodes || [];
  const edges = graph?.edges || [];
  if (countEl) countEl.textContent = `${nodes.length} Nodes · ${edges.length} Edges Linked (Neo4j)`;

  if (cypherCodeEl) {
    cypherCodeEl.textContent = graph?.cypherScript || generateFallbackCypherScript(graph);
  }

  // 1. Render Visual SVG Canvas
  renderVisualSvgGraph(nodes, edges);

  // 2. Render Node Breakdown Badges
  if (nodes.length === 0) {
    container.innerHTML = `<span style="font-size:0.8rem; color:var(--text-muted);">No linked identity nodes found.</span>`;
    return;
  }

  container.innerHTML = nodes.map(n => {
    let badgeColor = 'rgba(6,182,212,0.15); color:var(--cyan); border:1px solid rgba(6,182,212,0.35);';
    let icon = '🏷️';

    if (n.type === 'CANONICAL_PERSON_ROOT') {
      badgeColor = 'rgba(16,185,129,0.2); color:var(--emerald); border:1px solid rgba(16,185,129,0.4); font-weight:700;';
      icon = '👤 Root:';
    } else if (n.type === 'NAME_ALIAS') {
      badgeColor = 'rgba(245,158,11,0.15); color:var(--amber); border:1px solid rgba(245,158,11,0.35);';
      icon = '🔤 Alias:';
    } else if (n.type === 'EMAIL_IDENTIFIER') {
      badgeColor = 'rgba(139,92,246,0.15); color:#a78bfa; border:1px solid rgba(139,92,246,0.35);';
      icon = '✉️';
    } else if (n.type === 'PHONE_IDENTIFIER') {
      badgeColor = 'rgba(59,130,246,0.15); color:#60a5fa; border:1px solid rgba(59,130,246,0.35);';
      icon = '📱';
    } else if (n.type === 'SYSTEM_RECORD' || n.type === 'DISCOVERED_RECORD') {
      badgeColor = 'rgba(16,185,129,0.15); color:#34d399; border:1px solid rgba(16,185,129,0.35);';
      icon = '🗄️ Record:';
    } else if (n.type === 'NLP_EXTRACTED_ENTITY') {
      badgeColor = 'rgba(236,72,153,0.15); color:#f472b6; border:1px solid rgba(236,72,153,0.35);';
      icon = '🤖 NLP:';
    }

    return `
      <span class="meta-pill" style="${badgeColor} font-size:0.75rem; display:inline-flex; align-items:center; gap:4px; padding:4px 10px; border-radius:12px;">
        <span>${icon}</span>
        <span>${escapeHtml(n.label)}</span>
      </span>
    `;
  }).join('');
}

function renderDataMapTable(dataMap) {
  const tbody = document.getElementById('dsar-discovery-table-body');
  if (!tbody) return;

  const tables = dataMap.discoveredTables || [];

  if (tables.length === 0) {
    tbody.innerHTML = `
      <tr>
        <td colspan="6" style="text-align:center; padding:20px; color:var(--text-muted);">
          No connected systems or database tables found.
        </td>
      </tr>
    `;
    return;
  }

  tbody.innerHTML = tables.map(t => {
    const isFound = t.recordCount > 0;
    const statusBadge = isFound
      ? '<span class="meta-pill badge-verified" style="font-size:0.75rem;">✓ PII DISCOVERED</span>'
      : '<span class="meta-pill" style="opacity:0.5; font-size:0.75rem;">NO PII MATCH</span>';

    const fieldsBadge = (t.matchedFields || []).length > 0
      ? t.matchedFields.map(f => `<span class="meta-pill primary" style="font-size:0.72rem; margin-right:4px;">${escapeHtml(f)}</span>`).join('')
      : '<span style="color:var(--text-muted); font-size:0.8rem;">-</span>';

    const matchMethod = t.matchMethod || 'SQL Exact Check';
    const aiConfidence = t.aiConfidence || (isFound ? '97% High Confidence' : '0%');
    const systemBadge = formatSystemName(t.systemName, t.tableName);

    let confBadgeStyle = 'color:var(--text-muted);';
    if (aiConfidence.includes('97') || aiConfidence.includes('100') || aiConfidence.includes('High') || aiConfidence.includes('Direct')) {
      confBadgeStyle = 'color:var(--emerald); font-weight:700;';
    } else if (aiConfidence.includes('Probable') || aiConfidence.includes('82') || aiConfidence.includes('91')) {
      confBadgeStyle = 'color:var(--amber); font-weight:700;';
    }

    return `
      <tr style="vertical-align:middle;">
        <td style="padding:12px 14px;">${systemBadge}</td>
        <td style="padding:12px 14px;">${fieldsBadge}</td>
        <td style="padding:12px 14px; font-size:0.82rem; color:var(--text-bright); font-weight:600;">${escapeHtml(matchMethod)}</td>
        <td style="padding:12px 14px; font-size:0.82rem; ${confBadgeStyle}">${escapeHtml(aiConfidence)}</td>
        <td style="padding:12px 14px; font-weight:700; color:${isFound ? 'var(--emerald)' : 'var(--text-muted)'};">${t.recordCount} Record${t.recordCount === 1 ? '' : 's'}</td>
        <td style="padding:12px 14px;">${statusBadge}</td>
      </tr>
    `;
  }).join('');
}

export async function runIdentityDiscoveryScan(requestId) {
  if (!requestId) return;
  activeTargetRequestId = requestId;

  const card = document.getElementById('dsar-step2-discovery-card');
  const reqIdEl = document.getElementById('dsar-discovery-req-id');
  const nameEl = document.getElementById('dsar-disc-name');
  const emailEl = document.getElementById('dsar-disc-email');
  const phoneEl = document.getElementById('dsar-disc-phone');
  const confEl = document.getElementById('dsar-disc-confidence');
  const totalRecEl = document.getElementById('dsar-disc-total-records');
  const tbody = document.getElementById('dsar-discovery-table-body');

  if (card) card.classList.remove('hidden');
  if (reqIdEl) reqIdEl.textContent = `Target: ${requestId}`;

  // Update Stepper Bar to Step 2 Active
  updateStepperActiveStep(2);

  if (tbody) {
    tbody.innerHTML = `
      <tr>
        <td colspan="6" style="text-align:center; padding:24px; color:var(--cyan); font-weight:600;">
          <div style="display:inline-flex; align-items:center; gap:8px;">
            <svg width="18" height="18" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" class="spin"><polyline points="23 4 23 10 17 10"/><path d="M20.49 15a9 9 0 1 1-2.12-9.36L23 10"/></svg>
            <span>Running 8-Stage AI Identity Resolution & PII Discovery for ${escapeHtml(requestId)}…</span>
          </div>
        </td>
      </tr>
    `;
  }

  showToast(`Running 8-Stage AI Identity Resolution for ${requestId}…`, 'info');

  try {
    const res = await fetch(`${window.location.origin}/api/dsar/discovery/scan`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ requestId })
    });

    const data = await res.json();

    if (data && data.success && data.dataMap) {
      const dm = data.dataMap;
      if (nameEl) nameEl.textContent = dm.fullName || dm.targetDataSubject || 'N/A';
      if (emailEl) emailEl.textContent = dm.email || dm.targetEmail || 'N/A';
      if (phoneEl) phoneEl.textContent = dm.phone || dm.targetPhone || 'N/A';
      if (totalRecEl) totalRecEl.textContent = `${dm.totalPiiRecordsFound} Record${dm.totalPiiRecordsFound === 1 ? '' : 's'}`;

      if (confEl) {
        const confScore = dm.overallConfidence || (dm.totalPiiRecordsFound > 0 ? '97%' : '0%');
        const status = dm.overallStatus || 'MATCH';
        confEl.textContent = `${confScore} ${status.replace('_', ' ')}`;
        if (status === 'MATCH' || confScore.includes('9')) {
          confEl.style.color = 'var(--emerald)';
        } else if (status === 'PROBABLE_MATCH' || confScore.includes('8')) {
          confEl.style.color = 'var(--amber)';
        } else {
          confEl.style.color = 'var(--red)';
        }
      }

      renderIdentityGraphCluster(dm.identityGraph);
      renderDataMapTable(dm);
      showToast(`✓ Identity Discovery Complete! Discovered ${dm.totalPiiRecordsFound} PII record(s) across ${dm.systemsScanned || dm.discoveredSystemsCount} systems.`, 'success');

      if (card) card.scrollIntoView({ behavior: 'smooth' });
    } else {
      showToast(data.message || 'Failed to complete identity discovery scan', 'error');
    }
  } catch (err) {
    showToast(`Error running identity discovery scan: ${err.message}`, 'error');
  }
}

